export function getCandidateText(lang?: string, section?: string, key?: string) {
  const currentLang = lang || 'en';
  const dict = candidateTranslations[currentLang] || candidateTranslations['en'];
  
  if (!section) {
    return dict;
  }
  
  if (!key) {
    return dict[section] || candidateTranslations['en'][section] || {};
  }
  
  // Procura de forma segura com múltiplos fallbacks para evitar erros de undefined
  const val = dict[section]?.[key] 
    || dict['aiPanel']?.[key]
    || dict['dashboard']?.[key] 
    || dict[key] 
    || candidateTranslations['en'][section]?.[key] 
    || candidateTranslations['en']['aiPanel']?.[key]
    || candidateTranslations['en']['dashboard']?.[key] 
    || candidateTranslations['en'][key] 
    || '';
    
  return val;
}